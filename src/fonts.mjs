export const DEFAULT_FONT = "system";
export const isFontId = (id) => FONTS.some((font) => font.id === id);
export const getFont = (id) =>
  FONTS.find((font) => font.id === id) ||
  FONTS.find((font) => font.id === DEFAULT_FONT);
export const getFontStack = (id) => getFont(id).stack;
